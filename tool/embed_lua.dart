// Embeds the Lua modules of a widget package into a Dart file, so that the
// package ships them without assets:
//
//     dart run tool/embed_lua.dart packages/flutter_lua_bridge_ui uiLuaModules
//
// Every `lua/**/*.lua` of the package except `lua/test*/` becomes an entry
// of `const Map<String, String> <name>` in `lib/src/lua_modules.dart`, keyed
// by module name (`lua/flb/ui/prelude.lua` is `flb.ui.prelude`). The
// package's `test/catalog_test.dart` fails when the file is out of date.
import 'dart:io';

void main(List<String> args) {
  if (args.length != 2) {
    stderr.writeln('Usage: dart run tool/embed_lua.dart <package> <name>');
    exitCode = 64;
    return;
  }
  final package = Directory(args[0]);
  final name = args[1];
  final root = Directory('${package.path}/lua');
  final modules = <String, String>{};
  for (final file in root.listSync(recursive: true).whereType<File>()) {
    final relative = file.path.substring(root.path.length + 1);
    if (!relative.endsWith('.lua') || relative.startsWith('test')) continue;
    final module = relative
        .substring(0, relative.length - 4)
        .replaceAll(Platform.pathSeparator, '.');
    final source = file.readAsStringSync();
    if (source.contains("'''")) {
      throw FormatException(
        "${file.path} contains ''', which cannot be embedded",
      );
    }
    modules[module] = source;
  }
  final names = modules.keys.toList()..sort();
  final out = StringBuffer()
    ..writeln('// Generated by tool/embed_lua.dart from lua/. Do not edit.')
    ..writeln()
    ..writeln('/// The Lua modules of this package, by module name.')
    ..writeln('const Map<String, String> $name = {');
  for (final module in names) {
    out
      ..writeln("  '$module': r'''")
      ..write(modules[module])
      ..writeln("''',");
  }
  out.writeln('};');
  File('${package.path}/lib/src/lua_modules.dart')
      .writeAsStringSync(out.toString());
  stdout.writeln(
    '${names.length} modules -> ${package.path}/lib/src/lua_modules.dart',
  );
}
